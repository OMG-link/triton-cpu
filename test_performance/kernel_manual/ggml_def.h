// K 量化后 quant 位数 
// N 寄存器分块 nr 大小 
template <int K, int N> struct alignas(8)  block {
    ggml_half d[N];                         // deltas for N qK_0 blocks
    uint8_t    qs[(QK8_0 * N * K) / 8];         // quants for N qK_0 blocks : sizeof(qs) = 512 bytes
};

